import { api } from '../services/api';
import { useApi } from '../hooks/useApi';
import { PageLoader } from '../components/ui/Spinner';
import { ErrorState } from '../components/ui/states';
import { Card, CardHeader } from '../components/ui/Card';
import Badge from '../components/ui/Badge';
import PriceDistributionChart from '../components/charts/PriceDistributionChart';
import AreaPriceScatter from '../components/charts/AreaPriceScatter';
import CorrelationHeatmap from '../components/charts/CorrelationHeatmap';
import LocationBarChart from '../components/charts/LocationBarChart';
import ActualVsPredictedChart from '../components/charts/ActualVsPredictedChart';
import { R2ComparisonChart } from '../components/charts/ModelComparisonChart';
import { getApiErrorMessage } from '../services/api';

/**
 * Analytics page — every chart renders data computed by the backend from the
 * real dataset / real test-set predictions (GET /api/analytics, /api/metrics).
 * If a payload is missing the page shows an honest error, never fake data.
 */
export default function Analytics() {
  const { data: analytics, loading, error, refetch } = useApi(api.getAnalytics, []);
  const { data: metrics } = useApi(api.getMetrics, []);

  if (loading) return <PageLoader label="Crunching dataset visualisations…" />;

  if (error || !analytics) {
    return (
      <div className="mx-auto max-w-5xl px-4 pt-10 sm:px-6">
        <ErrorState
          title="Analytics unavailable"
          message={`${getApiErrorMessage(error)} Analytics data is generated by the training job (python -m ml.train).`}
          onRetry={refetch}
        />
      </div>
    );
  }

  const best = metrics?.best_model;
  const bestStats = best ? metrics.models.find((m) => m.model === best) : null;

  return (
    <div className="mx-auto max-w-6xl px-4 pb-16 pt-10 sm:px-6 lg:px-8">
      <header className="text-center">
        <span className="text-xs font-semibold uppercase tracking-[0.18em] text-emerald-300/90">Data Explorer</span>
        <h1 className="mt-2 text-3xl font-extrabold tracking-tight text-white sm:text-4xl">Analytics</h1>
        <p className="mx-auto mt-3 max-w-2xl text-sm text-slate-400 sm:text-base">
          Interactive views of the dataset and model behaviour — all series are served by the backend from the
          actual cleaned dataset and the selected model's test-set predictions.
        </p>
        <div className="mt-4 flex flex-wrap justify-center gap-2">
          <Badge variant="emerald">{analytics.area_vs_price.sample_size?.toLocaleString('en-IN')} sampled listings</Badge>
          <Badge variant="sky">{analytics.avg_price_by_location.length} cities</Badge>
          <Badge variant="amber">{analytics.actual_vs_predicted.sample_size?.toLocaleString('en-IN')} test predictions</Badge>
        </div>
      </header>

      <div className="mt-10 grid gap-6 lg:grid-cols-2">
        {/* 1. Price distribution */}
        <Card>
          <CardHeader
            title="1 · Price Distribution"
            description="How listing prices spread across the cleaned dataset."
          />
          <PriceDistributionChart bins={analytics.price_distribution} />
        </Card>

        {/* 2. Area vs Price */}
        <Card>
          <CardHeader
            title="2 · Area vs Price"
            description="Larger properties cost more — coloured by property type."
          />
          <AreaPriceScatter points={analytics.area_vs_price.points} />
        </Card>

        {/* 3. Correlation heatmap (full width) */}
        <Card className="lg:col-span-2">
          <CardHeader
            title="3 · Correlation Heatmap"
            description="Pearson correlation between numerical features and price — area and bedrooms dominate."
          />
          <CorrelationHeatmap columns={analytics.correlation.columns} matrix={analytics.correlation.matrix} />
        </Card>

        {/* 4. Average price by location */}
        <Card>
          <CardHeader
            title="4 · Average Price by Location"
            description="City means over all cleaned listings, sorted high → low."
          />
          <LocationBarChart data={analytics.avg_price_by_location} />
        </Card>

        {/* 5. Model performance comparison */}
        <Card>
          <CardHeader
            title="5 · Model Performance Comparison"
            description={best ? `${best} leads with test R² ${Number(bestStats?.R2 ?? 0).toFixed(4)}.` : 'Test R² per candidate model.'}
          />
          {metrics ? (
            <R2ComparisonChart models={metrics.models} />
          ) : (
            <p className="py-10 text-center text-sm text-slate-400" role="status">
              Model metrics could not be loaded — this chart needs /api/metrics.
            </p>
          )}
        </Card>

        {/* 6. Actual vs Predicted (full width) */}
        <Card className="lg:col-span-2">
          <CardHeader
            title="6 · Actual vs Predicted Prices"
            description={`Best model on the held-out test set (R² = ${Number(analytics.actual_vs_predicted.r2 ?? 0).toFixed(4)}). Points near the dashed line are accurate predictions.`}
          />
          <ActualVsPredictedChart
            points={analytics.actual_vs_predicted.points}
            r2={analytics.actual_vs_predicted.r2}
          />
        </Card>
      </div>
    </div>
  );
}

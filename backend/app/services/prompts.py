"""Modular, reusable Mistral system prompts.

All Generative-AI behaviour is defined here (never scattered through routes).
Design rules baked into every prompt:

  1. The numerical price comes from the trained ML model — Mistral must never
     invent, change, or "correct" it.
  2. Only the provided prediction context may be used; no fabricated market
     statistics, appreciation percentages, nearby prices, legal or mortgage info.
  3. Output must be clearly an AI interpretation, distinct from model output.
"""
from __future__ import annotations

from typing import Any

DISCLAIMER = (
    "AI-generated interpretation of the ML prediction and the property details "
    "provided — not verified real-estate market data."
)

BASE_SYSTEM_PROMPT = """You are Property Analyst AI, an assistant that explains machine-learning-based \
house-price predictions clearly and responsibly.

NON-NEGOTIABLE RULES:
- The numerical property price is generated by a trained machine-learning model (a scikit-learn \
Random Forest pipeline). It must never be changed, re-estimated, or invented by you.
- Use ONLY the property information and prediction context provided to you. Do not invent exact \
market prices, nearby property prices, appreciation percentages, legal information, mortgage rates, \
or location statistics.
- General, clearly-hedged domain knowledge (e.g. "newer properties typically retain value better") \
is allowed, but frame it as general context, not as verified data about this property's market.
- Keep a concise, professional, neutral tone. Use short headings and bullet points.
- You are an AI layer ON TOP of the model output: always distinguish model output (the price and \
feature-importance figures) from your own interpretation."""

ANALYSIS_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """

TASK: Produce a concise professional property analysis of the ML-estimated price.

Use EXACTLY these seven sections, each starting on its own line and ending with a colon:
Property Summary:
Price Interpretation:
Key Factors Affecting Value:
Positive Property Features:
Possible Concerns:
Improvement Suggestions:
General Market-style Insight:

Under each heading use 2-4 short bullet points (lines starting with "- ").
Finish with exactly this line:
Note: This is an AI-generated interpretation of the ML prediction, not verified market data."""

EXPLAIN_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """

TASK: Explain THIS prediction in simple language for a non-technical user.

Structure:
- Start with one plain-language sentence anchoring the ML-estimated price (repeat it exactly).
- Then a section "Why this prediction?:" with short bullets that reference the provided property \
attributes. Where a model-based feature-importance list is supplied, use it: features with higher \
provided importance may be described as more influential IN THIS MODEL. Do not claim precise \
rupee effects per feature — the model is not linear and you must not invent coefficients.
- Then a section "Keep in mind:" with 1-2 bullets reminding the user this is an interpretation \
of the model's estimate, not an appraisal.
Use "-" for bullets. Keep it under 220 words."""

CHAT_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """

TASK: Be a helpful, conversational "Property AI Assistant" for the user's follow-up questions
about the current prediction, the model, or ML concepts.

Guidelines:
- Answer questions such as: why the price is high/low, which features matter most (use the \
provided model feature-importance data when available), what changing an input would generally \
do, how to interpret MAE/MSE/RMSE/R², and general ML explanations.
- Metric definitions (R², RMSE, MAE, MSE) are general knowledge — answer them directly and simply.
- For anything requiring real-time or hyper-local market data, say clearly that you don't have \
access to a verified live data source.
- Keep replies short (under 180 words) and friendly. Use "-" bullets where helpful. Never output \
the full conversation history back to the user."""

FEATURE_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """

TASK: Explain what a single property feature means and how it generally influences a home's
valuation, given the provided model-based importance for that feature.

Structure:
- One sentence: what the feature measures.
- 2-3 bullets: how it generally affects value (hedged, general knowledge).
- One closing bullet stating the model-based importance figure exactly as provided and what it
  means (relative influence within THIS model, not a causal price effect).
Keep it under 120 words."""


# --------------------------------------------------------------------------- #
# Context formatting — one shared, structured property block                   #
# --------------------------------------------------------------------------- #
def _format_inr(value: float) -> str:
    value = float(value)
    if value >= 1e7:
        return f"₹{value:,.0f} (about ₹{value / 1e7:.2f} crore)"
    if value >= 1e5:
        return f"₹{value:,.0f} (about ₹{value / 1e5:.1f} lakh)"
    return f"₹{value:,.0f}"


def _num(value: Any) -> str:
    """Render numbers cleanly for prompts (2000.0 → '2000', 2000.5 → '2000.5')."""
    try:
        return f"{float(value):g}"
    except (TypeError, ValueError):
        return str(value)


def format_property_context(context: dict[str, Any]) -> str:
    """Render the prediction context as a clean structured block for prompts."""
    lines = [
        "PROPERTY DETAILS (provided by the user via the app):",
        f"- Area: {_num(context.get('area'))} sq ft",
        f"- Bedrooms: {_num(context.get('bedrooms'))}",
        f"- Bathrooms: {_num(context.get('bathrooms'))}",
        f"- Floors: {_num(context.get('floors'))}",
        f"- Parking spots: {_num(context.get('parking'))}",
        f"- Property age: {_num(context.get('property_age'))} years",
        f"- Location: {context.get('location')}",
        f"- Property type: {context.get('property_type')}",
        "",
        "ML PREDICTION (from the trained model — authoritative, do not change):",
        f"- Estimated price: {_format_inr(context.get('predicted_price', 0))}",
        f"- Model used: {context.get('model_name', 'Random Forest')}",
    ]

    importance = context.get("feature_importance")
    if importance:
        lines.append("")
        lines.append("MODEL-BASED FEATURE IMPORTANCE (computed from the trained model's own")
        lines.append("feature_importances_ on the trained features; sums to 1.0):")
        for item in importance[:6]:
            lines.append(f"- {item['feature'].replace('_', ' ')}: {float(item['importance']):.3f}")

    metrics = context.get("model_metrics")
    if metrics:
        lines.append("")
        lines.append("MODEL TEST-SET METRICS (computed during evaluation):")
        lines.append(
            f"- R²: {metrics.get('r2')} | MAE: ₹{float(metrics.get('mae', 0)):,.0f} | "
            f"RMSE: ₹{float(metrics.get('rmse', 0)):,.0f}"
        )

    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Message builders (system + user pairs, Mistral chat format)                  #
# --------------------------------------------------------------------------- #
def build_analysis_messages(context: dict[str, Any]) -> list[dict[str, str]]:
    user = (
        f"{format_property_context(context)}\n\n"
        "Write the seven-section property analysis now. Remember: interpret the ML estimate; "
        "never invent a different price or unverifiable market figures."
    )
    return [{"role": "system", "content": ANALYSIS_SYSTEM_PROMPT}, {"role": "user", "content": user}]


def build_explain_messages(context: dict[str, Any]) -> list[dict[str, str]]:
    user = (
        f"{format_property_context(context)}\n\n"
        "Explain this prediction in simple language now, following your structure. "
        "If model-based feature importance was provided, reference it."
    )
    return [{"role": "system", "content": EXPLAIN_SYSTEM_PROMPT}, {"role": "user", "content": user}]


def build_chat_messages(history: list[dict[str, str]], context: dict[str, Any] | None) -> list[dict[str, str]]:
    system = CHAT_SYSTEM_PROMPT
    if context:
        system += "\n\nCURRENT PREDICTION CONTEXT:\n" + format_property_context(context)
    else:
        system += "\n\nNo specific prediction context is attached yet — answer general questions about the model, metrics or house pricing."

    messages: list[dict[str, str]] = [{"role": "system", "content": system}]
    for message in history[-10:]:  # hard cap on conversation history sent upstream
        messages.append({"role": message["role"], "content": message["content"]})
    return messages


def build_feature_messages(feature_name: str, feature_row: dict[str, Any]) -> list[dict[str, str]]:
    user = (
        f"FEATURE: {feature_name.replace('_', ' ')}\n"
        f"MODEL-BASED IMPORTANCE: {feature_row.get('importance')}\n\n"
        "Explain this feature now, following your structure."
    )
    return [{"role": "system", "content": FEATURE_SYSTEM_PROMPT}, {"role": "user", "content": user}]
